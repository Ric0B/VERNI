#!/usr/bin/env python3
"""Woven (net) lamp shades as direct G-code: no slicer, non-planar, FullControl style.

The nozzle climbs in one continuous spiral, but in the woven part each lap
waves UP AND DOWN (in Z) as it goes round. The number of waves per lap is a
half-integer (e.g. 40.5), so each lap is in anti-phase with the lap below:
its low points land on the high points of the lap below (that is where the
strands fuse) and in between the strands bridge over open diamond cells.
The result is a real see-through net, which a normal slicer cannot make.

  foot band   solid spiral, 0.2 mm laps, for the base groove and adhesion
  net         laps spaced 2*A + h apart; strands touch at the wave tips
  rim band    solid spiral again, bridging over the last tips

    python3 weave.py                                   # out/weave/gewebe-test.gcode (+ previews)
    python3 weave.py --height 220 --radius 70 --waves 52.5 --amp 1.4 --name gewebe-lampe

Start/end G-code are minimal and generic. For the best first layer paste your
printer's own start G-code into start_<printer>.gcode next to this file (replace
Bambu's [placeholders] with numbers); it is used automatically if present.
"""
import argparse
import math
import os

TAU = 2 * math.pi
HERE = os.path.dirname(os.path.abspath(__file__))
FIL_AREA = math.pi * (1.75 / 2) ** 2

PRINTERS = {  # bed centre (X, Y) and usable size, mm
    "h2s": dict(cx=170.0, cy=160.0, size=(340, 320, 340)),
    "h2d": dict(cx=175.0, cy=160.0, size=(325, 320, 325)),
}


def smooth(a, b, x):
    t = min(1.0, max(0.0, (x - a) / (b - a)))
    return t * t * (3 - 2 * t)


def profile(z, a):
    """Radius of the shade at height z: a soft belly."""
    t = min(1.0, max(0.0, z / a.height))
    return a.radius + a.belly * math.sin(math.pi * t) ** 1.3


def plateau(s, flat):
    """Wave in -1..1 with flattened tips, so neighbouring laps share a short contact instead of a point."""
    return max(-1.0, min(1.0, s * (1 + flat)))


def toolpath(a):
    """Yield (x, y, z, h) along the path. Phases: foot band, net, rim band (all one continuous spiral)."""
    step = 0.45
    pitch_net = 2 * a.amp + a.strand_h            # centre-to-centre lap spacing in the net
    zc = a.first                                  # height of the lap centreline
    th = 0.0
    phase = "foot"
    amp_now = 0.0
    while True:
        if phase == "foot" and zc >= a.band:
            phase, ramp_start = "net", th
        if phase == "net" and zc + amp_now >= a.height - a.rim:
            phase, ramp_start = "rim", th
        if phase == "rim" and zc >= a.height:
            break
        r = profile(zc, a)
        dth = step / r
        if phase == "foot":
            pitch, amp_now, h = a.layer, 0.0, a.layer
        elif phase == "net":
            k = min(1.0, (th - ramp_start) / TAU)          # one lap to blend in
            amp_now = a.amp * k
            pitch = a.layer + (pitch_net - a.layer) * k
            h = a.strand_h
        else:
            k = min(1.0, (th - ramp_start) / TAU)
            amp_now = a.amp * (1 - k)
            pitch = pitch_net + (a.layer - pitch_net) * k
            h = a.layer if k >= 1 else a.strand_h
        zc += pitch * dth / TAU
        th += dth
        w = plateau(math.sin(a.waves * th), a.flat)
        z = zc + amp_now * w
        rr = r + a.radial * math.sin(a.waves * th) if phase == "net" else r
        yield rr * math.cos(th), rr * math.sin(th), z, h


def brim(a, loops=4):
    r0 = profile(0, a)
    for k in range(loops, 0, -1):
        r = r0 + k * a.width * 0.9
        pts = [(r * math.cos(TAU * j / 360), r * math.sin(TAU * j / 360)) for j in range(361)]
        yield pts


START = """; ---- minimal start G-code (generic). Replace with your printer's own for best results.
M140 S{bed}
M104 S170
G28
M190 S{bed}
M109 S{nozzle}
G90
M83
G92 E0
M106 P1 S0
G1 Z5 F1200
G1 X{px0:.1f} Y{py:.1f} F9000
G1 Z{z:.2f} F600
G1 X{px1:.1f} Y{py:.1f} E14 F1200 ; purge line
G1 Y{py2:.1f} F1200
G1 X{px0:.1f} Y{py2:.1f} E10 F1200
G1 Z1 F600
"""
END = """; ---- end
G1 Z{zup:.1f} F600
M104 S0
M140 S0
M106 P1 S0
G1 X{cx:.1f} Y{yaway:.1f} F6000
M84
"""


def write(a):
    pr = PRINTERS[a.printer]
    cx, cy = pr["cx"], pr["cy"]
    out_dir = os.path.join(HERE, "out", "weave")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, f"{a.name}.gcode")
    custom = os.path.join(HERE, f"start_{a.printer}.gcode")
    lines = [f"; Schichtlicht woven shade '{a.name}' generated by weave.py",
             f"; height {a.height} mm, radius {a.radius}+{a.belly} mm, waves/lap {a.waves}, net amp {a.amp} mm, strand {a.strand_h} mm",
             f"; layer {a.layer} mm, line width {a.width} mm, nozzle {a.nozzle_d} mm, {a.temp} C / bed {a.bed} C, PLA 1.75 mm",
             f"; printer {a.printer}, centre X{cx} Y{cy}"]
    if os.path.exists(custom):
        lines.append(open(custom, encoding="utf-8").read())
    else:
        lines.append(START.format(bed=a.bed, nozzle=a.temp, px0=cx - 60, px1=cx + 60, py=12.0, py2=12.6, z=a.first))
    e_rate = a.width / FIL_AREA                    # filament mm per (mm path * mm height)
    length = 0.0
    filament = 0.0
    # brim
    lines.append("; brim")
    for k, pts in enumerate(brim(a)):
        x0, y0 = pts[0]
        lines.append(f"G1 X{cx + x0:.3f} Y{cy + y0:.3f} F6000")
        lines.append(f"G1 Z{a.first:.3f} F600")
        for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
            d = math.hypot(x2 - x1, y2 - y1)
            e = d * a.first * e_rate * 1.05
            filament += e
            length += d
            lines.append(f"G1 X{cx + x2:.3f} Y{cy + y2:.3f} E{e:.5f} F{a.speed_first * 60:.0f}")
    # spiral
    lines.append("; woven spiral")
    prev = None
    fan_on = False
    zmax = 0
    rmax = 0
    for x, y, z, heff in toolpath(a):
        rmax = max(rmax, math.hypot(x, y))
        if prev is None:
            lines.append(f"G1 X{cx + x:.3f} Y{cy + y:.3f} F6000")
            lines.append(f"G1 Z{z:.3f} F600")
            prev = (x, y, z)
            continue
        d = math.dist(prev, (x, y, z))
        first_layers = z < a.first + 2 * a.layer
        h = a.first if first_layers else heff
        in_net = heff == a.strand_h
        e = d * h * e_rate * a.flow
        filament += e
        length += d
        if z > a.first + 3 * a.layer and not fan_on:
            lines.append(f"M106 P1 S{int(255 * a.fan / 100)}")
            fan_on = True
        speed = a.speed_first if first_layers else (a.speed if in_net else a.speed_band)
        lines.append(f"G1 X{cx + x:.3f} Y{cy + y:.3f} Z{z:.3f} E{e:.5f} F{speed * 60:.0f}")
        prev = (x, y, z)
        zmax = z
    lines.append(END.format(zup=zmax + 15, cx=cx, yaway=pr["size"][1] - 10))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    grams = filament * FIL_AREA / 1000 * 1.24
    hours = length / a.speed / 3600 * 1.15
    return path, dict(height=zmax, diameter=2 * rmax, path_m=length / 1000, grams=grams, hours=hours,
                      fits=2 * rmax + 20 < min(pr["size"][:2]) and zmax < pr["size"][2])


def preview(a, png):
    """Two quick looks before printing: the whole shade from the side, and an unrolled close-up of the net
    at true strand width, so you can see the open cells and the contact points."""
    from PIL import Image, ImageDraw
    pts = list(toolpath(a))
    W, H = 900, 1100
    scale = min((W - 120) / (2 * (a.radius + a.belly + 5)), (H - 120) / a.height)
    img = Image.new("RGB", (W, H), (14, 16, 19))
    dr = ImageDraw.Draw(img)
    P = lambda x, z: (W / 2 + x * scale, H - 60 - z * scale)
    for front in (False, True):
        col = (236, 218, 184) if front else (70, 64, 54)
        for (x1, y1, z1, _), (x2, y2, z2, _) in zip(pts, pts[1:]):
            if (y1 < 0) == front:
                dr.line([P(x1, z1), P(x2, z2)], fill=col, width=1)
    img.save(png)
    # unrolled close-up: 60 mm of circumference, 24 mm of height across the foot band into the net
    zs, ze, span = a.band - 6, a.band + 18, 60.0
    S = 22.0                                   # pixels per mm
    cw, ch = int(span * S), int((ze - zs) * S)
    im2 = Image.new("RGB", (cw, ch), (14, 16, 19))
    d2 = ImageDraw.Draw(im2)
    lw = max(2, int(a.width * S))
    th_total = 0.0
    prev = None
    for x, y, z, h in pts:
        th = math.atan2(y, x)
        if prev is not None:
            dth = th - prev[3]
            if dth < -math.pi:
                dth += TAU
            th_total += dth
        r = math.hypot(x, y)
        s_arc = (th_total % TAU) * r
        if prev is not None and zs - 1 < z < ze + 1 and s_arc < span and prev[0] < s_arc:
            lap = int(th_total // TAU)
            col = (236, 218, 184) if lap % 2 else (201, 160, 96)
            d2.line([(prev[0] * S, ch - (prev[1] - zs) * S), (s_arc * S, ch - (z - zs) * S)], fill=col, width=int(lw * h / a.strand_h) if h < a.strand_h else lw)
        prev = (s_arc, z, None, th)
    im2.save(png.replace(".png", "-closeup.png"))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", default="gewebe-test")
    ap.add_argument("--printer", choices=PRINTERS, default="h2s")
    ap.add_argument("--height", type=float, default=100)
    ap.add_argument("--radius", type=float, default=55, help="radius at foot and rim, mm (wall centre)")
    ap.add_argument("--belly", type=float, default=12, help="extra radius in the middle, mm")
    ap.add_argument("--waves", type=float, default=36.5, help="waves per lap; keep it x.5 so laps alternate")
    ap.add_argument("--amp", type=float, default=1.6, help="vertical wave amplitude in the net, mm (hole height = 2*amp)")
    ap.add_argument("--flat", type=float, default=0.35, help="flattens the wave tips for longer fused contacts")
    ap.add_argument("--strand-h", type=float, default=0.45, help="strand height in the net, mm")
    ap.add_argument("--radial", type=float, default=0.0, help="optional in/out wave too, mm (texture)")
    ap.add_argument("--band", type=float, default=6, help="solid band at the foot, mm")
    ap.add_argument("--rim", type=float, default=5, help="solid band at the rim, mm")
    ap.add_argument("--layer", type=float, default=0.2)
    ap.add_argument("--first", type=float, default=0.3, help="first layer height")
    ap.add_argument("--width", type=float, default=0.55, help="line width (0.4 nozzle: 0.5-0.6)")
    ap.add_argument("--nozzle-d", type=float, default=0.4)
    ap.add_argument("--flow", type=float, default=1.0)
    ap.add_argument("--temp", type=int, default=220)
    ap.add_argument("--bed", type=int, default=55)
    ap.add_argument("--fan", type=int, default=100)
    ap.add_argument("--speed", type=float, default=15, help="mm/s in the net (bridging strands: keep slow)")
    ap.add_argument("--speed-band", type=float, default=45)
    ap.add_argument("--speed-first", type=float, default=20)
    ap.add_argument("--no-preview", action="store_true")
    a = ap.parse_args()
    if abs(a.waves * 2 - round(a.waves * 2)) > 1e-9 or round(a.waves * 2) % 2 == 0:
        ap.error("--waves must end in .5 (e.g. 40.5) so neighbouring laps are in anti-phase")
    path, s = write(a)
    if not a.no_preview:
        preview(a, path.replace(".gcode", ".png"))
    print(f"{path}\n  {s['height']:.0f} mm tall, Ø {s['diameter']:.0f} mm, path {s['path_m']:.0f} m, "
          f"about {s['grams']:.0f} g PLA, about {s['hours']:.1f} h, fits {a.printer}: {s['fits']}")


if __name__ == "__main__":
    main()
